/** Busca por nombre o alias, insensible a mayúsculas/acentos. */
export function findCfMovement(query: string): CfMovementDef | undefined {
  const q = normalizeCfText(query).trim()
  if (!q) { return undefined }
  return CF_MOVEMENTS.find(
    (m) => normalizeCfText(m.name) === q || m.aliases.some((a) => normalizeCfText(a) === q),
  )
}

/** Normaliza texto para búsqueda: minúsculas y sin acentos. */
export function normalizeCfText(text: string): string {
  return text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
}

