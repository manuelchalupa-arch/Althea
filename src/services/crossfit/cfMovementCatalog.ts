import type { CfModality, CfLevel } from './types'

export type CfCategory = 'gimnasia' | 'weightlifting' | 'metcon' | 'complementario'
export type CfIntensity = 'baja' | 'media' | 'alta'

export interface CfMovementDef {
  /** id estable en kebab-case, p.ej. 'cf-bar-muscle-up' */
  id: string
  /** Nombre canónico en inglés tal como se usa en WODs, p.ej. 'Bar Muscle-Up' */
  name: string
  /** Variantes de nombre para búsqueda (español, siglas), p.ej. ['muscle up en barra','BMU'] */
  aliases: string[]
  modality: CfModality
  category: CfCategory
  equipment: string[]
  level: 'principiante' | 'intermedio' | 'avanzado'
  /** Patrón biomecánico: reutiliza el vocabulario del Exercise general de Althea */
  pattern: 'push' | 'pull' | 'squat' | 'hinge' | 'lunge' | 'carry' | 'core' | 'full'
  description: string
  /** Pasos de ejecución (3-5 bullets cortos) */
  technique: string[]
  /** Grupos musculares principales */
  muscles: string[]
  /** Errores frecuentes (2-4 bullets) */
  errors: string[]
  variants: string[]
  progressions: string[]
  regressions: string[]
  /** Sustituciones por nivel de escalado. El nivel 'adapted' es por lesión/movilidad: ORIENTATIVO, no médico. */
  scale: Partial<Record<CfLevel, string>>
  /** Demanda cardiovascular percibida del movimiento aislado */
  cardio: CfIntensity
  /** Complejidad coordinativa */
  coordination: CfIntensity
  /** Requerimientos de movilidad (articulaciones), p.ej. ['hombros','cadera'] */
  mobility: string[]
}

